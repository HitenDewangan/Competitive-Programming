class student:
    def __init__(self, id, major, hobby):
        self.id = id
        self.major = major
        self.hobby = hobby

stu1 = student(1, "CSE", "Gaming")

print(stu1.id)
print(stu1.major)
print(stu1.hobby)

# here we have created an object of class student and called it stu1